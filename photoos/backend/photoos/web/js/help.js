/**
 * PhotoOS · 使用说明（「说明」页的全部内容与渲染）
 *
 * ## 为什么按界面分节，而不是按功能模块分节
 *
 * 用户是先在界面上碰到一个问题（"这个筛选怎么筛不出我的照片"），才会想知道原因。
 * 所以每一节都从"在哪个标签页做"开头，再写要动手做哪几步，最后写这一步做不到什么。
 * `tab` 用界面上的标签名（照片库 / 精选 / 找照片 / 人物 / 主题 / 维护），
 * 用户能在界面上一眼对上号。
 *
 * ## 为什么是这个顺序
 *
 *  看全库 → 收新照片 → 逐组精选 → 找照片（按内容 / 按修改 / 按时间）→ 人物 → 主题
 *  → 维护与换盘 → 数据放在哪里
 *
 * 前九节是"怎么用"，按日常干活的顺序排；最后一节回答的是"我的照片会不会被动"——
 * 这个问题不适合打断前面的操作流程，但必须是整页的结论，所以放在最后。
 *
 * ## 为什么限制写得这么具体（"标签轴返回 501""模型分不清日出与日落"）
 *
 * 含糊的限制等于没有限制。用户只有知道边界在哪，才不会把"搜不到"误当成"库里没有"，
 * 也不会因为一个做不到的事反复重试。宁可写"这里做不到"，也不写听起来好听的概括。
 *
 * 零构建：原生 ES module。只依赖共享工具模块（无副作用的转义工具）；
 * 不从主应用模块取任何东西 —— 导入它会在导入的同时把整个应用再启动一遍。
 */

