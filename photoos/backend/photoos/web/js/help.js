/** 锚点名：加前缀避免和页面上已有的元素 id 撞名（那里也有 `library` 之类的名字）。 */
function anchorOf(section) {
  return `help-${section.id}`;
}

/** 一个列表项：数组里放的永远是纯文本，转义后塞进 li。 */
function listItems(tag, values, className, label) {
  const items = values.map((text) => `<li>${escapeHtml(text)}</li>`).join('');
  return `<${tag} class="${className}" aria-label="${escapeHtml(label)}">${items}</${tag}>`;
}

/**
 * 把说明渲染进 container。
 *
 * 为什么整块用 innerHTML 一次写入、而不是逐个 createElement：
 * 这一页是纯静态内容（没有交互、没有事件绑定），一次写入最省事；
 * 只要每一个来自数据的字符串都过了 escapeHtml，就没有注入的余地。
 * 目录里的锚点链接用浏览器自带的行为跳转即可，不需要脚本参与。
 */
export function renderHelp(container) {
  if (!container) return;

  const toc = HELP_SECTIONS.map((section) => `
    <li>
      <a href="#${escapeHtml(anchorOf(section))}">
        <span class="help-toc-tab">${escapeHtml(section.tab)}</span>
        <span class="help-toc-title">${escapeHtml(section.title)}</span>
      </a>
    </li>`).join('');

  const body = HELP_SECTIONS.map((section) => {
    const cli = section.cli && section.cli.length
      ? `<pre class="help-cli" aria-label="等价的命令行命令">${
        escapeHtml(section.cli.join('\n'))}</pre>`
      : '';
    return `
    <section class="help-section" id="${escapeHtml(anchorOf(section))}">
      <h2>${escapeHtml(section.title)}</h2>
      <p class="help-what">${escapeHtml(section.what)}</p>
      ${listItems('ol', section.how, 'help-how', '怎么做')}
      ${listItems('ul', section.limits, 'help-limits', '限制与注意事项')}
      ${cli}
    </section>`;
  }).join('');

  container.innerHTML = `
    <nav class="help-toc" aria-label="目录">
      <p class="help-toc-head">目录</p>
      <ol class="help-toc-list">${toc}</ol>
    </nav>
    ${body}
    <p class="help-version hint tiny">说明版本 ${escapeHtml(HELP_VERSION)}</p>`;
}
